import { open, st, ticking, until } from './qa_lib.mjs';
const { browser, page, logs } = await open('http://localhost:5231/?seed=1');
console.log('start', await ticking(page));
await page.keyboard.down('Space'); await page.waitForTimeout(400);
console.log('holding', await st(page));
await page.keyboard.up('Space'); await page.waitForTimeout(300);
console.log('released', await st(page), await page.evaluate(()=>window.__game.game.firedThisTurn));
await page.screenshot({ path: '/tmp/qa_m2/u1_first_space.png' });
console.log('turn2', await until(page, s=>s.turn===2));
console.log(await page.evaluate(()=>window.__game.game.teams.map(t=>t.lastWeapon)));
await page.screenshot({ path: '/tmp/qa_m2/u1_turn2_prompt.png' });
await page.keyboard.press('F4'); await page.waitForTimeout(300);
console.log('after F4', await st(page));
await page.keyboard.press('Space'); await page.waitForTimeout(100);
console.log('turn3', await until(page, s=>s.turn===3));
console.log('turn3 weapon (team A last used bazooka)');
await page.keyboard.press('KeyZ'); await page.waitForTimeout(300);
console.log(await st(page));
await page.keyboard.press('Space');
console.log('turn4', await until(page, s=>s.turn===4));
console.log(await page.evaluate(()=>window.__game.game.teams.map(t=>t.lastWeapon)));
await page.keyboard.press('KeyZ'); await page.waitForTimeout(300);
console.log('turn4 active weapon', (await st(page)).weapon);
console.log(logs.filter(l=>!l.includes('Graphics')));
await browser.close();
